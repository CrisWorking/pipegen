// C6 (ruling S5): the gate's built-in view of the reviewed list, generated at build time into gate/src/generated/gate-view.ts.
// The bundle holds this module, never the loader or data/reviewed-tools.yml: nothing is read from disk at run time, and the view holds no
// pins (so the gate's own entry creates no fixpoint). `npm run build:gate` writes it (tsup.gate.config.ts); CI's gate-dist job diffs it.
import { gateToolView } from '../gate/src/settings.js';
import type { ReviewedTool } from '../src/types.js';

/** The text of gate/src/generated/gate-view.ts for a reviewed list. Pure, so the same list always gives the same bytes. */
export function gateViewModule(list: readonly ReviewedTool[]): string {
  return [
    '// GENERATED by scripts/gate-view.ts (run by `npm run build:gate`) from data/reviewed-tools.yml. Do not edit.',
    '// The gate\'s built-in view of the reviewed list (ruling S5): no pins, nothing read from disk at run time.',
    "import type { GateToolView } from '../settings.js';",
    '',
    `export const GATE_VIEW: readonly GateToolView[] = ${JSON.stringify(gateToolView(list), null, 2)};`,
    '',
  ].join('\n');
}
